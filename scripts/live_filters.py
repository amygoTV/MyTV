#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""直播源频道名过滤规则（构建侧与校验侧共用）。

判定标准（按用户 2026-11-23 要求）：
  * 台标/频道名正确的正常频道一律保留，即使正在插播广告；
  * 只剔除频道名本身就是广告/购物/测试/博彩的台；
  * 错台、纯广告画面、测试卡由 scripts/ad_blacklist.txt 人工确认后按 URL 拉黑。

本模块只做名称判定，不抽帧、不看画面内容，也不判断 URL。
"""
import re

# 电视台分组（央视/卫视/港澳台/央视付费/海外频道）的频道名过滤。
# 正常频道名（CCTV-1、湖南卫视、凤凰卫视、CETV-1 等）不会命中；
# 这里只按“频道名/台标”判断，不因为正常频道播放广告而删除。
AD_NAME_RE = re.compile(
    r"(广告|购物|电视购物|推广|促销|推销|热卖|抢购|订购|商城|带货|卖货|"
    r"福利|红包|抽奖|秒杀|特价|优惠|团购|折扣|清仓|甩卖|"
    r"赚钱|赚米|兼职|招聘|招工|招生|培训|"
    r"测试|測試|test|试用|彩条|"
    r"扫码|二维码|加群|QQ群|微信群|私信|加微信|公众号|更多资源|获取资源|"
    r"网址|官网|客服|热线|咨询|办理|开户|"
    r"话费|流量|保健|理财|贷款|保险|"
    r"彩票|福彩|体彩|竞彩|棋牌|博彩|赌场|赌博|六合彩|时时彩|"
    r"PK10|北京赛车|幸运飞艇|百家乐|老虎机|真人娱乐|电子游艺|"
    r"招商|加盟|厂家|厂价|工厂直销|批发|货源|拿货|库存|特卖|正品|代购|微商|"
    r"下单|回收|二手|装修|年货|求购|需求度|官方直播间)",
    re.I,
)

# 上游列表里的说明/维护/失效提示行，不是频道，不能进入产物。
NOISE_NAME_RE = re.compile(
    r"(支持作者|感谢|订阅|请\s*user|请查看最新|请访问|请到|"
    r"失效|版权|声明|免责|列表更新时间|更新时间|维护中?|"
    r"暫無|暂无主播|温馨|提示|答疑|教程|^\d+$|^\d{4}[-/]\d{1,2})",
    re.I,
)

# 影视轮播 / B站 / 体育房间名的垃圾过滤（沿用 v1.6.x 构建脚本的既有规则）。
# 房间名常直接使用片名，因此不套用上面的电视台名称规则，避免误杀《购物狂》等片名。
SPAM_NAME_RE = re.compile(
    r'(支持作者|感谢|订阅|广告|推广|二维码|扫码|公众号|更多资源|获取资源|'
    r'请\s*user|请查看最新|请访问|请到|失效|版权|声明|免责|'
    r'列表更新时间|更新时间|维护中?|暫無|暂无主播|温馨|提示|'
    r'答疑|教程|招聘|兼职|赚钱|赚米|卖货|厂价|厂家|优惠|团购|工厂直销|'
    r'官方直播间|需求度|求购|招商|加盟|福利|抽奖|秒杀|特价|批发|货源|'
    r'下单|客服|咨询|办理|开户|彩票|贷款|回收|二手|装修|培训|招生|'
    r'年货|特卖|清仓|库存|拿货|正品|代购|微商|私信|加微信|福利彩票|'
    r'测试|測試|test|^\d+$|^\d{4}[-/]\d{1,2})', re.I)


def is_ad_channel_name(name):
    """频道名本身是广告/购物/测试/博彩台。"""
    return bool(AD_NAME_RE.search(name or ''))


def is_noise_name(name):
    """不是频道，而是说明/维护/失效提示。"""
    return bool(NOISE_NAME_RE.search(name or ''))


def is_dropped_tv_name(name):
    """电视台分组里应剔除的名称。"""
    return is_ad_channel_name(name) or is_noise_name(name)


def is_spam_name(name):
    """影视轮播/B站/体育房间名的垃圾过滤。"""
    return bool(SPAM_NAME_RE.search(name or ''))
